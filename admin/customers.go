// List searches customers.
//
// Supported q attributes: id, number, email, link_number,
// billing_address_s_full_tel, created_at, updated_at, with_deleted,
// member_groups_id, line_id_linked_at (lighter only).
// Supported sort attributes: id, created_at, updated_at.
// Supported include values: billing_address, shipping_addresses, notes,
// points, one_d_color_answers, one_d_color_answers.scores, orders,
// subs_orders, credit_cards, member_groups.
//
// ecforce API docs: GET /api/v2/admin/customers
func (s *CustomersService) List(ctx context.Context, opts *ecforce.ListOptions) ([]*ecforce.Resource[Customer], *ecforce.Response, error) {
	return ecforce.DoResourceList[Customer](ctx, s.client, http.MethodGet, "admin/customers.json", opts.Values(), nil)
}

// Get fetches a single customer.
//
// Supported include values: billing_address, shipping_addresses, notes,
// points, one_d_color_answers, one_d_color_answers.scores, orders,
// subs_orders, credit_cards, member_groups, customer_permitted_variants.
//
// ecforce API docs: GET /api/v2/admin/customers/:customer_id
func (s *CustomersService) Get(ctx context.Context, customerID int64, opts *ecforce.GetOptions) (*ecforce.Resource[Customer], *ecforce.Response, error) {
	path := fmt.Sprintf("admin/customers/%d.json", customerID)
	return ecforce.DoResource[Customer](ctx, s.client, http.MethodGet, path, opts.Values(), nil)
}

