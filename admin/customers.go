// NoteParams sets a customer memo on update requests. An entry with an ID
// updates (or, with Delete, removes) that memo; an entry without one adds a
// new memo.
type NoteParams struct {
	ID         *int64           `json:"id,omitempty"`
	Content    *string          `json:"content,omitempty"`
	OperatedAt *ecforce.Time    `json:"operated_at,omitempty"`
	OperatedBy *int64           `json:"operated_by,omitempty"`
	Delete     *ecforce.BoolInt `json:"delete,omitempty"`
}

// CustomerPermittedVariantParams sets a customer-limited variant on update
// requests. An entry with an ID updates (or, with Delete, removes) that
// setting; an entry without one adds a new setting.
type CustomerPermittedVariantParams struct {
	ID        *int64           `json:"id,omitempty"`
	VariantID *int64           `json:"variant_id,omitempty"`
	StartedAt *ecforce.Time    `json:"started_at,omitempty"`
	EndedAt   *ecforce.Time    `json:"ended_at,omitempty"`
	Delete    *ecforce.BoolInt `json:"delete,omitempty"`
}

// PointParams creates a point ledger entry. For CreatePoint, set PointEventID
// (WithCreate false) or Name/Description (WithCreate true), Point as an
// absolute value, and AdditionAndSubtraction (false: subtract, true: add).
// As CustomerParams.PointAttributes, only PointEventID and Point apply.
type PointParams struct {
	PointEventID           *int64           `json:"point_event_id,omitempty"`
	Name                   *string          `json:"name,omitempty"`
	Description            *string          `json:"description,omitempty"`
	Point                  *int             `json:"point,omitempty"`
	AdditionAndSubtraction *ecforce.BoolInt `json:"addition_and_subtraction,omitempty"`
	WithCreate             *ecforce.BoolInt `json:"with_create,omitempty"`
}

// CustomerPointParams is one entry of a BulkCreatePoints request.
type CustomerPointParams struct {
	CustomerID             *int64           `json:"customer_id,omitempty"`
	PointEventID           *int64           `json:"point_event_id,omitempty"`
	Point                  *int             `json:"point,omitempty"`
	AdditionAndSubtraction *ecforce.BoolInt `json:"addition_and_subtraction,omitempty"`
}

